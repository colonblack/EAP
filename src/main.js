/* ========================================
   Language switching
   ======================================== */

let currentLang = 'fr';

// Update translated text, the page title, and the selected language button.
const setLanguage = (lang) => {
  currentLang = lang;
  document.documentElement.lang = lang;

  // Update elements containing plain text.
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;

    if (key && copy[lang][key]) {
      element.textContent = copy[lang][key];
    }
  });

  // Update headings containing safe formatting such as <br> and <em>.
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const key = element.dataset.i18nHtml;

    if (key && copy[lang][key]) {
      element.innerHTML = copy[lang][key];
    }
  });

  // Mark the active language button visually and for screen readers.
  document.querySelectorAll('.lang').forEach((button) => {
    const isActive = button.dataset.lang === lang;

    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  document.title = lang === 'fr'
    ? 'Église Apostolique de Pentecôte'
    : 'Apostolic Pentecostal Church';

  localStorage.setItem('eap-lang', lang);
};

// Listen for clicks on the FR and EN language buttons.
document.querySelectorAll('.lang').forEach((button) => {
  button.addEventListener('click', () => {
    setLanguage(button.dataset.lang);
  });
});

/* ========================================
   Mobile navigation
   ======================================== */

const menu = document.querySelector('#main-nav');
const menuButton = document.querySelector('.menu-toggle');

// Open or close the mobile menu from the hamburger button.
menuButton?.addEventListener('click', () => {
  const isOpen = menu?.classList.toggle('open') ?? false;
  menuButton.setAttribute('aria-expanded', String(isOpen));
});

// Close the mobile menu after the visitor chooses a navigation link.
menu?.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => {
    menu.classList.remove('open');
    menuButton?.setAttribute('aria-expanded', 'false');
  });
});

/* ========================================
   Contact form
   ======================================== */

const contactForm = document.querySelector('#contact-form');

// Show a translated confirmation and clear the form after submission.
contactForm?.addEventListener('submit', (event) => {
  event.preventDefault();

  const status = document.querySelector('.form-status');

  if (status) {
    status.textContent = copy[currentLang].success;
  }

  event.currentTarget.reset();
});

/* ========================================
   Scroll reveal animations
   ======================================== */

// Reveal each marked element once it enters the visitor's viewport.
const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll('.reveal').forEach((element) => {
  revealObserver.observe(element);
});

/* ========================================
   Page initialization
   ======================================== */

// Restore the visitor's saved language, defaulting to French.
const savedLanguage = localStorage.getItem('eap-lang');
setLanguage(savedLanguage === 'en' ? 'en' : 'fr');

// Keep the footer copyright year current automatically.
const year = document.querySelector('#year');

if (year) {
  year.textContent = String(new Date().getFullYear());
}
